#!/usr/bin/env bash
set -euo pipefail

# Copies the built paywall platform script into this package as a generated
# Swift constant, mirroring
# sdks/react-native/coproduct/scripts/sync-onboarding-platform-script.sh's
# approach exactly.
#
# The platform script (packages/paywall-platform-script) is owned by the
# coproduct-platform repo, checked out as a sibling of this repo
# (coproduct-client-sdks), not inside this monorepo. Adjust
# PLATFORM_SCRIPT_REPO below if your checkout layout differs.
#
# Run after any change to that package.

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
PLATFORM_SCRIPT_REPO="${PLATFORM_SCRIPT_REPO:-$ROOT/../coproduct-platform}"
PLATFORM_SCRIPT_PKG="$PLATFORM_SCRIPT_REPO/packages/paywall-platform-script"

if [ ! -d "$PLATFORM_SCRIPT_PKG" ]; then
  echo "error: $PLATFORM_SCRIPT_PKG not found." >&2
  echo "packages/paywall-platform-script does not exist yet in coproduct-platform" >&2
  echo "(it builds the shared WebView bridge script this package embeds)." >&2
  echo "Set PLATFORM_SCRIPT_REPO to override the coproduct-platform checkout path." >&2
  exit 1
fi

(cd "$PLATFORM_SCRIPT_REPO" && pnpm --filter @coproduct/paywall-platform-script run build)

BUILT_JS="$PLATFORM_SCRIPT_PKG/dist/paywall-platform-script.js"
OUT_FILE="$ROOT/sdks/ios/Sources/Coproduct/Paywall/PaywallPlatformScript.generated.swift"

{
  echo "// Generated by scripts/sync-ios-paywall-platform-script.sh from the"
  echo "// paywall-platform-script package in the sibling coproduct-platform"
  echo "// repo. Do not hand-edit -- re-run this script after any change to"
  echo "// that package. A stale or placeholder value here fails silently at"
  echo "// runtime: the paywall feature it's missing just never triggers."
  printf 'let paywallPlatformScriptJs = %s\n' "$(node -e "console.log(JSON.stringify(require('fs').readFileSync('$BUILT_JS', 'utf8')))")"
} > "$OUT_FILE"

echo "Synced PaywallPlatformScript.generated.swift (paywall)"
