#!/usr/bin/env bash
# Regenerates sdks/android/src/main/kotlin/app/coproduct/paywall/PlatformScript.kt
# from the sibling coproduct-platform repo's compiled paywall platform
# script. Mirrors the equivalent Flutter/RN sync scripts. Run this from a
# machine with a coproduct-platform checkout alongside this one.
set -euo pipefail

PLATFORM_REPO="${COPRODUCT_PLATFORM_REPO:-../coproduct-platform}"
SOURCE_FILE="$PLATFORM_REPO/packages/paywall-platform-script/dist/paywall-platform-script.js"
OUTPUT_FILE="sdks/android/src/main/kotlin/app/coproduct/paywall/PlatformScript.kt"

if [[ ! -f "$SOURCE_FILE" ]]; then
  echo "error: $SOURCE_FILE not found. Set COPRODUCT_PLATFORM_REPO to a coproduct-platform checkout with the paywall platform script built." >&2
  exit 1
fi

{
  echo "package app.coproduct.paywall"
  echo
  echo "// Generated by scripts/sync-paywall-platform-script.sh. Do not hand-edit."
  echo "internal val platformScriptJs: String = \"\"\""
  sed 's/\$/\\$/g' "$SOURCE_FILE"
  echo "\"\"\""
} > "$OUTPUT_FILE"

echo "Wrote $OUTPUT_FILE from $SOURCE_FILE"
